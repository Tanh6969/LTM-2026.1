INSERT INTO Flights (flight_number, airline_id, aircraft_type, departure_city, arrival_city, departure_airport, arrival_airport, departure_time, arrival_time, status)
SELECT r.num || '-' || to_char(d.day, 'MMDD'),
       a.airline_id, r.aircraft, r.dcity, r.acity, r.dairport, r.aairport,
       (d.day + make_interval(hours => r.dhour, mins => r.dmin)) AT TIME ZONE 'Asia/Ho_Chi_Minh',
       (d.day + make_interval(hours => r.dhour, mins => r.dmin + r.dur_min)) AT TIME ZONE 'Asia/Ho_Chi_Minh',
       'On Time'
FROM _routes r
  JOIN Airlines a ON a.code = r.airline_code
  CROSS JOIN LATERAL (
    SELECT (date_trunc('day', now() AT TIME ZONE 'Asia/Ho_Chi_Minh') + make_interval(days => n)) AS day
    FROM generate_series(1, 7) n
  ) d;


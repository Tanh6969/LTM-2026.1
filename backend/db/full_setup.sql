CREATE FUNCTION pg_temp.add_ticket(
  p_booking BIGINT, p_flight BIGINT, p_class flight_class, p_seat TEXT,
  p_first TEXT, p_last TEXT, p_status ticket_status DEFAULT 'Active'
) RETURNS BIGINT AS $$
DECLARE
  v_seat BIGINT;
  v_ticket BIGINT;
BEGIN
  SELECT seat_id INTO v_seat FROM Seats WHERE flight_id = p_flight AND seat_code = p_seat;
  INSERT INTO Tickets (ticket_code, seat_id, flight_class, price, status, booking_id, flight_id)
  VALUES ('T' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 12)),
          v_seat, p_class,
          (SELECT price FROM FlightFares WHERE flight_id = p_flight AND class = p_class),
          p_status, p_booking, p_flight)
  RETURNING ticket_id INTO v_ticket;
  INSERT INTO TicketOwnerSnapshots (ticket_id, first_name, last_name, gender)
  VALUES (v_ticket, p_first, p_last, 'Other');
  RETURN v_ticket;
END;
$$ LANGUAGE plpgsql;


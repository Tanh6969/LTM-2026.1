CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------- Dọn sạch ----------
DROP TABLE IF EXISTS TicketChanges, Notifications, FlightStatusHistory, Payments,
  TicketOwnerSnapshots, Tickets, Seats, Bookings, FlightFares, Flights, Airlines,
  News, Admins, Customers, Users, schema_migrations CASCADE;

DROP TYPE IF EXISTS user_role, gender_type, trip_type, booking_status, ticket_status,
  flight_status, flight_class, seat_status, payment_method, payment_status, notification_type CASCADE;

DROP FUNCTION IF EXISTS set_updated_at_column() CASCADE;

-- ---------- Enum ----------
CREATE TYPE user_role AS ENUM ('customer', 'admin');
CREATE TYPE gender_type AS ENUM ('Male', 'Female', 'Other');
CREATE TYPE trip_type AS ENUM ('oneWay', 'roundTrip');
CREATE TYPE booking_status AS ENUM ('confirmed', 'cancelled', 'pending', 'expired');
CREATE TYPE ticket_status AS ENUM ('Active', 'Cancelled', 'Changed', 'CheckedIn');
CREATE TYPE flight_status AS ENUM ('On Time', 'Delayed', 'Cancelled', 'Boarding', 'Takeoff', 'Landing', 'Landed');
CREATE TYPE flight_class AS ENUM ('economy', 'business', 'firstClass');
CREATE TYPE seat_status AS ENUM ('available', 'held', 'booked');
CREATE TYPE payment_method AS ENUM ('card', 'ewallet');
CREATE TYPE payment_status AS ENUM ('pending', 'succeeded', 'failed', 'refunded');
CREATE TYPE notification_type AS ENUM (
  'DELAYED', 'CANCELLED', 'RESCHEDULED', 'STATUS_CHANGED',
  'BOOKING_CONFIRMED', 'TICKET_CANCELLED', 'TICKET_CHANGED'
);

-- ---------- Trigger updated_at dùng chung ----------
CREATE FUNCTION set_updated_at_column() RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------- Users (khách hàng + admin, phân biệt bằng role) ----------
CREATE TABLE Users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) UNIQUE NOT NULL,
  hashed_password VARCHAR(255) NOT NULL,
  first_name VARCHAR(100),
  last_name VARCHAR(100),
  role user_role NOT NULL DEFAULT 'customer',
  phone_number VARCHAR(20),
  gender gender_type NOT NULL DEFAULT 'Other',
  date_of_birth DATE,
  passport_number VARCHAR(50),
  identification_number VARCHAR(50),
  address TEXT,
  loyalty_points INT DEFAULT 0 CHECK (loyalty_points >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  deleted_at timestamptz DEFAULT NULL,
  created_at timestamptz NOT NULL DEFAULT (now()),
  updated_at timestamptz NOT NULL DEFAULT (now())
);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON Users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at_column();

-- ---------- News ----------
CREATE TABLE News (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  content TEXT,
  image TEXT,
  author_id BIGINT REFERENCES Users(user_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT (now()),
  updated_at timestamptz NOT NULL DEFAULT (now())
);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON News
  FOR EACH ROW EXECUTE FUNCTION set_updated_at_column();

-- ---------- Airlines / Flights / Fares ----------
CREATE TABLE Airlines (
  airline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(3) UNIQUE NOT NULL,
  name VARCHAR(100) UNIQUE NOT NULL,
  logo_url TEXT
);

CREATE TABLE Flights (
  flight_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_number VARCHAR(20) UNIQUE NOT NULL,
  airline_id BIGINT NOT NULL REFERENCES Airlines(airline_id),
  aircraft_type VARCHAR(100),
  departure_city VARCHAR(100),
  arrival_city VARCHAR(100),
  departure_airport VARCHAR(255),
  arrival_airport VARCHAR(255),
  departure_time TIMESTAMPTZ NOT NULL,
  arrival_time TIMESTAMPTZ NOT NULL,
  total_seats_row INT NOT NULL CHECK (total_seats_row > 0) DEFAULT 44,
  total_seats_column INT NOT NULL CHECK (total_seats_column > 0) DEFAULT 6,
  status flight_status NOT NULL DEFAULT 'On Time',
  CONSTRAINT departure_before_arrival CHECK (departure_time < arrival_time)
);

CREATE INDEX idx_flights_departure_time ON Flights (departure_time);
CREATE INDEX idx_flights_arrival_time ON Flights (arrival_time);
CREATE INDEX idx_flights_status ON Flights (status);
CREATE INDEX idx_flights_route_time ON Flights (departure_city, arrival_city, departure_time);
CREATE INDEX idx_flights_airline_id ON Flights (airline_id);

CREATE TABLE FlightFares (
  flight_id BIGINT NOT NULL REFERENCES Flights(flight_id) ON DELETE CASCADE,
  class flight_class NOT NULL,
  price INT NOT NULL CHECK (price >= 0),
  seats_total INT NOT NULL CHECK (seats_total >= 0),
  PRIMARY KEY (flight_id, class)
);

-- ---------- Bookings (user_id NULL = khách vãng lai) ----------
CREATE TABLE Bookings (
  booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pnr VARCHAR(6) UNIQUE NOT NULL,
  user_id BIGINT REFERENCES Users(user_id) ON DELETE SET NULL,
  contact_name VARCHAR(200) NOT NULL,
  contact_email VARCHAR(255) NOT NULL,
  contact_phone VARCHAR(20) NOT NULL,
  trip_type trip_type NOT NULL,
  departure_flight_id BIGINT NOT NULL REFERENCES Flights(flight_id) ON DELETE CASCADE,
  return_flight_id BIGINT REFERENCES Flights(flight_id) ON DELETE CASCADE,
  status booking_status NOT NULL DEFAULT 'pending',
  total_amount INT NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
  hold_expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT (now()),
  updated_at timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT bookings_trip_return_check CHECK (
    (trip_type = 'oneWay' AND return_flight_id IS NULL)
    OR (trip_type = 'roundTrip' AND return_flight_id IS NOT NULL)
  )
);

CREATE INDEX idx_bookings_user_id ON Bookings (user_id);
CREATE INDEX idx_bookings_pnr_email ON Bookings (pnr, contact_email);
CREATE INDEX idx_bookings_departure_flight_id ON Bookings (departure_flight_id);
CREATE INDEX idx_bookings_return_flight_id ON Bookings (return_flight_id);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON Bookings
  FOR EACH ROW EXECUTE FUNCTION set_updated_at_column();

-- ---------- Seats / Tickets ----------
CREATE TABLE Seats (
  seat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id BIGINT NOT NULL REFERENCES Flights(flight_id) ON DELETE CASCADE,
  seat_code VARCHAR(4) NOT NULL,
  class flight_class NOT NULL DEFAULT 'economy',
  status seat_status NOT NULL DEFAULT 'available',
  held_until timestamptz,
  held_by_booking BIGINT REFERENCES Bookings(booking_id) ON DELETE SET NULL,
  UNIQUE (flight_id, seat_code)
);

CREATE TABLE Tickets (
  ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_code VARCHAR(13) UNIQUE NOT NULL,
  seat_id BIGINT REFERENCES Seats(seat_id) ON DELETE SET NULL,
  flight_class flight_class NOT NULL DEFAULT 'economy',
  price INT NOT NULL CHECK (price >= 0),
  status ticket_status NOT NULL DEFAULT 'Active',
  booking_id BIGINT REFERENCES Bookings(booking_id) ON DELETE CASCADE,
  flight_id BIGINT NOT NULL REFERENCES Flights(flight_id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT (now()),
  updated_at timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX idx_tickets_booking_id ON Tickets (booking_id);
CREATE INDEX idx_tickets_flight_id ON Tickets (flight_id);
-- Một ghế chỉ thuộc về một vé còn hiệu lực
CREATE UNIQUE INDEX uq_tickets_active_seat ON Tickets (seat_id)
  WHERE seat_id IS NOT NULL AND status IN ('Active', 'CheckedIn');

CREATE TRIGGER set_updated_at BEFORE UPDATE ON Tickets
  FOR EACH ROW EXECUTE FUNCTION set_updated_at_column();

CREATE TABLE TicketOwnerSnapshots (
  ticket_id BIGINT PRIMARY KEY REFERENCES Tickets(ticket_id) ON DELETE CASCADE,
  first_name VARCHAR(100),
  last_name VARCHAR(100),
  phone_number VARCHAR(20),
  gender gender_type NOT NULL DEFAULT 'Other',
  date_of_birth DATE,
  passport_number VARCHAR(50),
  identification_number VARCHAR(50),
  address TEXT
);

CREATE TABLE TicketChanges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  old_ticket_id BIGINT NOT NULL REFERENCES Tickets(ticket_id) ON DELETE CASCADE,
  new_ticket_id BIGINT NOT NULL REFERENCES Tickets(ticket_id) ON DELETE CASCADE,
  change_fee INT NOT NULL DEFAULT 0 CHECK (change_fee >= 0),
  fare_difference INT NOT NULL DEFAULT 0,
  changed_at timestamptz NOT NULL DEFAULT (now())
);

-- ---------- Payments / Notifications / FlightStatusHistory ----------
CREATE TABLE Payments (
  payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES Bookings(booking_id) ON DELETE CASCADE,
  method payment_method NOT NULL,
  provider VARCHAR(30),
  provider_ref VARCHAR(255),
  amount INT NOT NULL,
  status payment_status NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX idx_payments_booking_id ON Payments (booking_id);
CREATE INDEX idx_payments_created_at ON Payments (created_at);

CREATE TABLE FlightStatusHistory (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id BIGINT NOT NULL REFERENCES Flights(flight_id) ON DELETE CASCADE,
  old_status flight_status,
  new_status flight_status NOT NULL,
  old_departure_time timestamptz,
  new_departure_time timestamptz,
  reason TEXT,
  changed_by BIGINT REFERENCES Users(user_id) ON DELETE SET NULL,
  changed_at timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX idx_fsh_flight_id ON FlightStatusHistory (flight_id, changed_at DESC);

CREATE TABLE Notifications (
  notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES Users(user_id) ON DELETE CASCADE,
  booking_id BIGINT REFERENCES Bookings(booking_id) ON DELETE CASCADE,
  flight_id BIGINT REFERENCES Flights(flight_id) ON DELETE CASCADE,
  type notification_type NOT NULL,
  title VARCHAR(255) NOT NULL,
  message TEXT,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  sent_email BOOLEAN NOT NULL DEFAULT FALSE,
  created_at timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX idx_notifications_user ON Notifications (user_id, is_read);
CREATE INDEX idx_notifications_booking ON Notifications (booking_id);


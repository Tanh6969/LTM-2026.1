-- ---------- Airlines ----------
CREATE TABLE Airlines (
  airline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(3) UNIQUE NOT NULL,
  name VARCHAR(100) UNIQUE NOT NULL,
  logo_url TEXT
);

INSERT INTO
  Airlines (code, name)
SELECT
  MIN(UPPER(LEFT(flight_number, 2))),
  COALESCE(airline, 'Unknown')
FROM
  Flights
GROUP BY
  COALESCE(airline, 'Unknown');

ALTER TABLE
  Flights
ADD
  COLUMN airline_id BIGINT REFERENCES Airlines(airline_id);

UPDATE
  Flights f
SET
  airline_id = a.airline_id
FROM
  Airlines a
WHERE
  a.name = COALESCE(f.airline, 'Unknown');

ALTER TABLE
  Flights
ALTER COLUMN
  airline_id
SET
  NOT NULL;

-- ---------- Flight fares: giá theo hạng ghế (thay base_price) ----------
CREATE TABLE FlightFares (
  flight_id BIGINT NOT NULL REFERENCES Flights(flight_id) ON DELETE CASCADE,
  class flight_class NOT NULL,
  price INT NOT NULL CHECK (price >= 0),
  seats_total INT NOT NULL CHECK (seats_total >= 0),
  PRIMARY KEY (flight_id, class)
);

-- Backfill: 4 hàng đầu là thương gia (giá x2), phần còn lại phổ thông
INSERT INTO
  FlightFares (flight_id, class, price, seats_total)
SELECT
  flight_id,
  'economy',
  base_price,
  GREATEST(total_seats_row - 4, 0) * total_seats_column
FROM
  Flights;

INSERT INTO
  FlightFares (flight_id, class, price, seats_total)
SELECT
  flight_id,
  'business',
  base_price * 2,
  LEAST(total_seats_row, 4) * total_seats_column
FROM
  Flights;

ALTER TABLE
  Flights DROP COLUMN base_price,
  DROP COLUMN airline;

CREATE INDEX idx_flights_route_time ON Flights (departure_city, arrival_city, departure_time);

CREATE INDEX idx_flights_airline_id ON Flights (airline_id);


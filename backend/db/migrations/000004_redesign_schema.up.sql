-- ---------- Payments ----------
CREATE TABLE Payments (
  payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES Bookings(booking_id) ON DELETE CASCADE,
  method payment_method NOT NULL,
  provider VARCHAR(30),
  provider_ref VARCHAR(255),
  amount INT NOT NULL,
  status payment_status NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX idx_payments_booking_id ON Payments (booking_id);

CREATE INDEX idx_payments_created_at ON Payments (created_at);

-- ---------- Lịch sử trạng thái chuyến bay (changed_by NULL = hệ thống tự động) ----------
CREATE TABLE FlightStatusHistory (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id BIGINT NOT NULL REFERENCES Flights(flight_id) ON DELETE CASCADE,
  old_status flight_status,
  new_status flight_status NOT NULL,
  old_departure_time timestamptz,
  new_departure_time timestamptz,
  reason TEXT,
  changed_by BIGINT REFERENCES Users(user_id) ON DELETE
  SET
    NULL,
    changed_at timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX idx_fsh_flight_id ON FlightStatusHistory (flight_id, changed_at DESC);

-- ---------- Thông báo ----------
CREATE TABLE Notifications (
  notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES Users(user_id) ON DELETE CASCADE,
  booking_id BIGINT REFERENCES Bookings(booking_id) ON DELETE CASCADE,
  flight_id BIGINT REFERENCES Flights(flight_id) ON DELETE CASCADE,
  type notification_type NOT NULL,
  title VARCHAR(255) NOT NULL,
  message TEXT,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  sent_email BOOLEAN NOT NULL DEFAULT FALSE,
  created_at timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX idx_notifications_user ON Notifications (user_id, is_read);

CREATE INDEX idx_notifications_booking ON Notifications (booking_id);

-- ---------- Lịch sử đổi vé ----------
CREATE TABLE TicketChanges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  old_ticket_id BIGINT NOT NULL REFERENCES Tickets(ticket_id) ON DELETE CASCADE,
  new_ticket_id BIGINT NOT NULL REFERENCES Tickets(ticket_id) ON DELETE CASCADE,
  change_fee INT NOT NULL DEFAULT 0 CHECK (change_fee >= 0),
  fare_difference INT NOT NULL DEFAULT 0,
  changed_at timestamptz NOT NULL DEFAULT (now())
);
